#!/bin/bash
# Builds the PC patcher: patcher/zelda3ds-patcher
#
#   ./build-patcher.sh                          no base build inside: pass
#                                               --base-cia/--base-3dsx when running
#   ./build-patcher.sh <base.cia> <base.3dsx>   release build: embeds the
#                                               asset-free base builds of the game
#
# Plain C++14, no dependencies. CXX/CXXFLAGS/OUT can be overridden (CI uses
# them to cross-build for Windows and to make a universal macOS binary).
set -euo pipefail
cd "$(dirname "$0")"
OUT="${OUT:-zelda3ds-patcher}"
EMBED=()
if [[ $# -eq 2 ]]; then
    GEN="$(mktemp -d)"
    python3 - "$1" "$2" "$GEN/embedded_base.h" <<'PY'
import sys
cia, dsx, out = sys.argv[1:4]
with open(out, "w") as f:
    f.write("// Generated by build-patcher.sh -- asset-free base builds of the game.\n#pragma once\n#include <stddef.h>\n")
    for name, path in (("kBaseCia", cia), ("kBase3dsx", dsx)):
        data = open(path, "rb").read()
        f.write("static const unsigned char %s[] = {\n" % name)
        for i in range(0, len(data), 32):
            f.write(",".join(str(b) for b in data[i:i+32]) + ",\n")
        f.write("};\nstatic const size_t %sSize = %d;\n" % (name, len(data)))
PY
    EMBED=( -DPATCHER_EMBED_BASE -I"$GEN" )
fi
${CXX:-c++} -std=c++14 -O2 -Wall ${CXXFLAGS:-} -Isrc -Isrc/extract "${EMBED[@]+"${EMBED[@]}"}" \
    -o "$OUT" src/patcher.cpp src/patch_core.cpp src/extract/RomExtract.cpp
echo "Built patcher/$OUT${EMBED[*]:+ (with base builds embedded)}"
